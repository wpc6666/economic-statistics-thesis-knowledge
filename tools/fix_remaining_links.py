def fix_cross_kp(fp, text):
    """处理 ../XX章/知识点/KPyy_简称 形式的链接"""
    in_kp_dir = fp.parent.name == "知识点"
    changed = [False]

    def repl3(m):
        inner = m.group(1)
        parts = inner.split("|")
        target = parts[0]
        # 匹配 ../XX章/知识点/KPyy_zzz 或 ../../XX章/知识点/...
        mt = re.match(r'^(\.\./)+(\d{2}_[^/]+)/知识点/(KP\d+[^|/#]*)', target)
        if not mt:
            return m.group(0)
        ups, chap, kp_short = mt.group(1), mt.group(2), mt.group(3)
        new_kp = SHORT_MAP.get((chap, kp_short), kp_short)
        # 层数：源在知识点目录下时，原写法 ../ 少一层
        if in_kp_dir and ups == "../":
            new_ups = "../../"
        else:
            new_ups = ups
        new_target = new_ups + chap + "/知识点/" + new_kp
        rest = inner[len(target):]
        changed[0] = True
        return f"[[{new_target}{rest}]]"

    text2 = re.sub(r'\[\[([^\[\]]*)\]\]', repl3, text)
    return text2, changed[0]

