changed_files = {}  # rel_path -> [ (old, new) ]

def rel(p):
    return str(Path(p).relative_to(ROOT))

def sub(rel_path, old, new):
    """在指定文件中把 wikilink 文本 old 替换为 new，返回是否替换成功"""
    fp = ROOT / rel_path
    text = fp.read_text(encoding="utf-8")
    cnt = text.count(old)
    if cnt == 0:
        print(f"  ⚠️ 未找到: {rel_path} :: {old}")
        return False
    text2 = text.replace(old, new)
    fp.write_text(text2, encoding="utf-8")
    changed_files.setdefault(rel_path, []).append((old, new))
    return True

